/**
 * Scope every `id` inside file-icons-data.ts to its own icon.
 *
 * WHY: the icon map is rendered with `dangerouslySetInnerHTML` into the live
 * document, and SVG `id` / `url(#id)` are DOCUMENT-global, not SVG-local. The
 * vscode-icons set reuses bare names (`a`, `b`, `c`, …), so 156 icons carry only
 * 65 distinct ids and 24 of them are shared — `id="a"` alone is defined by 36
 * icons. Whichever icon paints first wins the id for the whole page, and every
 * later icon that references it inherits a foreign filter/mask/gradient.
 *
 * That is not theoretical: `file_type_vite` defines and references `a` (a
 * `<mask>`) plus `b`, `c` (Gaussian blur filters). Once a `file_type_assembly`
 * row has painted earlier in the tree, the Vite glyph renders as a purple blob.
 * Verified with a headless-Chrome A/B render.
 *
 * FIX: rename each icon's ids to `<id>-<iconKey>` and rewrite its references to
 * match. Ids stay unique per icon regardless of paint order. Every icon is
 * self-contained (audited: 37 icons reference ids, all defined in their own
 * markup), so a per-icon rename is complete.
 *
 * Usage: node scripts/gen-file-icons.mjs [--check]
 *   --check  verify the file is already scoped; exit 1 if not (CI/pre-commit).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dataPath = join(root, 'plugins/dsh-codex/src/client/features/files/file-icons-data.ts')

/** One `"key": "<svg …>"` row of the generated map. */
const ROW = /^(\s*)"([a-z0-9_]+)":\s*"((?:[^"\\]|\\.)*)",\s*$/gm

const unescape = (s) => s.replace(/\\"/g, '"').replace(/\\\\/g, '\\')
const escape = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')

/**
 * The file header, owned here so neither invariant can be lost by a
 * regeneration.
 */
const HEADER = `/**
 * GENERATED by scripts/gen-file-icons.mjs — do not edit by hand.
 *
 * Icons: vscode-icons (https://github.com/vscode-icons/vscode-icons),
 * MIT License, Copyright (c) vscode-icons contributors.
 *
 * Each icon's internal \`id\`s are scoped to \`<id>-<iconKey>\`: these SVGs are
 * injected into one live document, where \`id\` and \`url(#id)\` are global, and
 * the upstream set reuses bare names (\`a\`, \`b\`, \`c\`…). Unscoped, the first icon
 * to paint owns the id for the whole page — a LICENSE row used to hijack the
 * Vite glyph's mask and filters.
 *
 * Every icon also carries a \`viewBox\`. The glyph slot is a fixed 16x16 box, so
 * an icon without one is clipped rather than scaled: \`file_type_dotenv\`'s 32x32
 * art showed as a solid gold square instead of the ".env" glyph.
 *
 * Re-run the generator after upgrading icons.
 */`

/** Replace the leading block comment (or prepend the header when absent). */
function withHeader(source, header) {
  const stripped = source.replace(/^\/\*\*[\s\S]*?\*\/\n/, '')
  return `${header}\n${stripped}`
}

/** Distinct `id="…"` values defined by one icon's markup. */
export function definedIds(svg) {
  return [...new Set([...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]))]
}

/** Every id one icon's markup references, across all three reference forms. */
export function referencedIds(svg) {
  return new Set([
    ...[...svg.matchAll(/url\(#([^)"']+)\)/g)].map((m) => m[1]),
    ...[...svg.matchAll(/xlink:href="#([^"]+)"/g)].map((m) => m[1]),
    ...[...svg.matchAll(/(?<!xlink:)href="#([^"]+)"/g)].map((m) => m[1]),
  ])
}

/**
 * Rename one icon's ids to `<id>-<key>` and rewrite its own references.
 *
 * Idempotent: an icon whose ids already end in `-<key>` is returned unchanged,
 * so re-running the generator (or a second --check) cannot double-scope an id
 * into `a-file_type_cargo-file_type_cargo`.
 *
 * @param svg - the icon's markup.
 * @param key - the icon's map key, used as the scope suffix.
 */
export function scopeIds(svg, key) {
  if (isScoped(svg, key)) return svg
  let out = svg
  for (const id of definedIds(svg)) {
    const scoped = `${id}-${key}`
    out = out.replaceAll(` id="${id}"`, ` id="${scoped}"`)
    out = out.replaceAll(`url(#${id})`, `url(#${scoped})`)
    out = out.replaceAll(`xlink:href="#${id}"`, `xlink:href="#${scoped}"`)
    out = out.replaceAll(`href="#${id}"`, `href="#${scoped}"`)
  }
  return out
}

/** Whether one icon's ids are already scoped to its key. */
function isScoped(svg, key) {
  const ids = definedIds(svg)
  return ids.length === 0 || ids.every((id) => id.endsWith(`-${key}`))
}

/**
 * Ensure one icon declares a `viewBox`.
 *
 * The glyph slot is a fixed 16x16 box (`styles.ts`: `svg{width:16px;height:16px}`),
 * so an icon with no `viewBox` is NOT scaled to fit — the browser shows the
 * user-space origin at 1:1 and clips everything past 16 units. `file_type_dotenv`
 * was the only icon missing one, and its 32x32 artwork cropped to the solid gold
 * background square the tree showed instead of the ".env" glyph.
 *
 * Deriving `viewBox="0 0 <width> <height>"` restores the intended scaling: that
 * is the SVG default when width/height are absolute, so this only makes explicit
 * what the artwork already assumed. An icon with neither attribute is left alone
 * and reported by the caller.
 *
 * @param svg - the icon's markup.
 */
export function ensureViewBox(svg) {
  if (/\sviewBox="/.test(svg)) return svg
  const width = /\swidth="([^"]+)"/.exec(svg)?.[1]
  const height = /\sheight="([^"]+)"/.exec(svg)?.[1]
  if (width === undefined || height === undefined) return svg
  return svg.replace(/<svg\b/, `<svg viewBox="0 0 ${width} ${height}"`)
}

/**
 * Normalize one icon for the glyph slot: scope its ids, then guarantee a viewBox.
 *
 * @param svg - the icon's markup.
 * @param key - the icon's map key, used as the id scope suffix.
 */
export function normalizeIcon(svg, key) {
  return ensureViewBox(scopeIds(svg, key))
}

function main() {
  const check = process.argv.includes('--check')
  const source = readFileSync(dataPath, 'utf8')

  const problems = []
  let icons = 0
  let scoped = 0
  let noViewBox = 0

  const output = withHeader(source.replace(ROW, (line, indent, key, raw) => {
    icons++
    const svg = unescape(raw)
    if (isScoped(svg, key)) scoped++
    if (!/\sviewBox="/.test(svg) && !/\swidth="/.test(svg)) noViewBox++

    // A reference to an id this icon does not define would stay dangling after
    // renaming, so the icon would lose the filter/mask it depends on.
    const own = new Set(definedIds(svg))
    for (const ref of referencedIds(svg)) {
      if (!own.has(ref)) problems.push(`${key} references id "${ref}" it does not define`)
    }
    return `${indent}"${key}": "${escape(normalizeIcon(svg, key))}",`
  }), HEADER)

  if (problems.length > 0) {
    console.error('file-icon scoping is unsafe:\n' + problems.map((p) => `- ${p}`).join('\n'))
    process.exitCode = 1
    return
  }

  if (noViewBox > 0) {
    console.error(
      `file icons missing both viewBox and width (cannot be sized in the 16px glyph slot): ${noViewBox}`,
    )
    process.exitCode = 1
    return
  }

  if (check) {
    // Compare the regenerated result rather than probing individual invariants,
    // so any drift (unscoped ids, a missing viewBox, a stale header) fails.
    if (output !== source) {
      const unscoped = icons - scoped
      console.error(
        'file icons are out of date' +
        (unscoped > 0 ? ` (${unscoped}/${icons} icons still use bare ids)` : '') +
        '.\nRun `node scripts/gen-file-icons.mjs` to regenerate them.',
      )
      process.exitCode = 1
      return
    }
    console.log(`file icons OK (${icons} icons, ids scoped and viewBox present)`)
    return
  }

  if (output === source) {
    console.log(`file icons already normalized (${icons} icons)`)
    return
  }
  writeFileSync(dataPath, output)
  const parts = []
  if (icons - scoped > 0) parts.push(`scoped ${icons - scoped}`)
  parts.push('normalized viewBox')
  console.log(`${parts.join('; ')} across ${icons} icons in file-icons-data.ts`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
